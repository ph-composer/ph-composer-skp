"""The outline map's border generator (tools/map_data/map_borders.py), on synthetic GeoJSON: the same source and
settings give the same bytes, only outer rings are kept, the United States and Canada come from their regions, and
every line fits the repository's limit. With the real Natural Earth files named by PH_COMPOSER_MAP_DATA, the
shipped module is checked against them; without them that check skips."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest

import map_borders

SHIPPED = Path(__file__).resolve().parents[2] / "src" / "ph_composer" / "html" / "map_borders.js"


def square(west: float, south: float, size: float) -> list[list[float]]:
    return [[west, south], [west + size, south], [west + size, south + size], [west, south + size], [west, south]]


def feature(properties: dict[str, str], rings: list[list[list[float]]]) -> dict[str, Any]:
    return {"type": "Feature", "properties": properties, "geometry": {"type": "Polygon", "coordinates": rings}}


def sources() -> tuple[dict[str, Any], dict[str, Any]]:
    countries = {
        "features": [
            feature({"ADM0_A3": "ZZB", "NAME": "Beta"}, [square(10, 10, 5)]),
            feature({"ADM0_A3": "ZZA", "NAME": "Alpha"}, [square(0, 0, 4), square(1, 1, 1)]),
            feature({"ADM0_A3": "USA", "NAME": "United States"}, [square(-100, 30, 20)]),
        ]
    }
    states = {
        "features": [
            feature({"adm0_a3": "USA", "iso_3166_2": "US-B", "name": "B"}, [square(-90, 30, 10)]),
            feature({"adm0_a3": "USA", "iso_3166_2": "US-A", "name": "A"}, [square(-100, 30, 10)]),
            feature({"adm0_a3": "MEX", "iso_3166_2": "MX-A", "name": "M"}, [square(-105, 20, 5)]),
        ]
    }
    return countries, states


def rings(text: str, layer: str) -> list[list[int]]:
    start = text.index(f'"{layer}": [')
    body = text[start + len(layer) + 4 : text.index("\n    ]", start) + 6]
    return map_borders.decode_layer(json.loads(body))


def test_the_polyline_encoding_round_trips() -> None:
    numbers = [0, 1, -1, 31, -32, 1000, -17999, 36000, 5]
    assert map_borders.polyline(numbers) == "?A@}@~@o}@|cb@_ieAI"
    # tests/outline_map_test.js decodes these two rings in the panel.
    assert map_borders.polyline([100, 200, 300, -400, -50, 60]) == "gEoKwQ~WbBwB"
    assert map_borders.polyline([-1000, -500, 10, 10, 0, -20]) == "n}@f^SS?f@"
    assert map_borders.unpolyline(map_borders.polyline(numbers)) == numbers
    assert all(63 <= ord(character) <= 126 for character in map_borders.polyline(numbers))


def test_the_same_source_and_settings_give_the_same_bytes() -> None:
    countries, states = sources()
    first = map_borders.build(countries, states, map_borders.Settings(), "test")
    shuffled_countries = {"features": list(reversed(countries["features"]))}
    shuffled_states = {"features": list(reversed(states["features"]))}
    assert map_borders.build(shuffled_countries, shuffled_states, map_borders.Settings(), "test") == first
    assert all(len(line) <= 120 for line in first.splitlines())


def test_outer_rings_only_with_the_us_and_canada_from_their_regions() -> None:
    countries, states = sources()
    text = map_borders.build(countries, states, map_borders.Settings(), "test")
    assert rings(text, "countries") == [[0, 0, 400, 0, 0, 400, -400, 0], [1000, 1000, 500, 0, 0, 500, -500, 0]]
    assert rings(text, "states") == [
        [-10000, 3000, 1000, 0, 0, 1000, -1000, 0],
        [-9000, 3000, 1000, 0, 0, 1000, -1000, 0],
    ]
    assert text.startswith("/* Generated by tools/map_data/map_borders.py")
    assert 'PhComposerUI.define("map_borders", [], function () {' in text


def test_a_ring_too_small_to_draw_is_dropped() -> None:
    assert map_borders.encode([(0, 0), (0.1, 0), (0.1, 0.1), (0, 0.1), (0, 0)], 0.01, 0.05) is None


@pytest.mark.skipif(not os.environ.get("PH_COMPOSER_MAP_DATA"), reason="PH_COMPOSER_MAP_DATA is not set")
def test_the_shipped_module_is_what_the_source_gives() -> None:
    folder = Path(os.environ["PH_COMPOSER_MAP_DATA"])
    countries = json.loads((folder / "ne_50m_admin_0_countries.geojson").read_text(encoding="utf-8"))
    states = json.loads((folder / "ne_50m_admin_1_states_provinces.geojson").read_text(encoding="utf-8"))
    text = map_borders.build(countries, states, map_borders.Settings(), "5.1.2")
    assert text == SHIPPED.read_text(encoding="utf-8")
