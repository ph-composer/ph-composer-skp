"use strict";
/* Captures every scene of a planning mockup built on the mockup kit (tools/ui-preview/.index.md, "Mockup
   kit"), then rewrites the scene table in the mockup's README.md. Run it with
   `make ui-gallery MOCKUP=planning/features/<slug>/mockups/<page>.html`, which serves the repository on a
   free port. PNGs land beside the page unless UI_GALLERY_OUT names a folder; UI_GALLERY_SCENES narrows the
   run to PNG names containing any of its words. A page error, a console error (an unknown `do=` step is
   one) or a shot whose selector matches nothing fails the run. A capture, not a check. */
const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");

const port = process.env.UI_PREVIEW_PORT || "8765";
const mockup = process.env.MOCKUP;
if (!mockup || !fs.existsSync(mockup)) {
  console.error(`mockup gallery: MOCKUP names no file (${mockup || "unset"}); pass a repository-relative path`);
  process.exit(1);
}
const dir = path.dirname(mockup);
const out = process.env.UI_GALLERY_OUT || dir;
const only = (process.env.UI_GALLERY_SCENES || "").split(/\s+/).filter(Boolean);
const url = `http://127.0.0.1:${port}/${mockup.split(path.sep).join("/")}`;

function query(shot) {
  const q = [`journey=${shot.journey || 1}`];
  if (shot.do) q.push(`do=${shot.do}`);
  return q.join("&");
}

// The README's scene table sits between these markers; the rest of the README stays as written.
const START = "<!-- mockup-scenes: generated by make ui-gallery; edit scenes.js, not this table -->";
const END = "<!-- /mockup-scenes -->";
function sceneTable(scenes) {
  const rows = scenes.map((g) => {
    const shots = g.shots.map((s) => {
      const extra = [s.size && s.size !== "1280x800" ? s.size : "", s.note || ""].filter(Boolean).join(", ");
      return `\`${s.png}\` (\`${query(s)}\`${extra ? ", " + extra : ""})`;
    });
    return `| ${g.group} | ${g.try || ""} | ${shots.join(", ")} |`;
  });
  return [START, "| Scene | What to try | PNGs |", "| --- | --- | --- |", ...rows, END].join("\n");
}
function writeTable(scenes) {
  const readme = path.join(dir, "README.md");
  if (!fs.existsSync(readme)) return console.log("mockup gallery: no README.md beside the page; table not written");
  const text = fs.readFileSync(readme, "utf8");
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < a) return console.log(`mockup gallery: README.md has no scene markers; add\n${START}\n${END}`);
  fs.writeFileSync(readme, text.slice(0, a) + sceneTable(scenes) + text.slice(b + END.length));
  console.log("table", readme);
}

(async () => {
  const browser = await chromium.launch({ headless: true, channel: "chrome" });
  const errors = [];
  const watch = (page, label) => {
    page.on("pageerror", (e) => errors.push(`${label}: ${e.message}`));
    // A failed load is reported by URL below; the browser's own favicon request is not the page's.
    page.on("console", (m) => { if (m.type() === "error" && !m.text().startsWith("Failed to load resource")) errors.push(`${label}: ${m.text()}`); });
    page.on("response", (r) => { if (r.status() >= 400 && !r.url().endsWith("/favicon.ico")) errors.push(`${label}: ${r.status()} ${r.url()}`); });
  };
  try {
    const probe = await browser.newPage();
    watch(probe, "load");
    await probe.goto(url);
    await probe.waitForSelector("html[data-mockup-ready]", { timeout: 5000 });
    const scenes = await probe.evaluate(() => (window.MOCKUP || {}).scenes || []);
    await probe.close();
    if (!scenes.length) throw new Error("the page lists no scenes (Mockup.start({ scenes }))");
    fs.mkdirSync(out, { recursive: true });
    for (const shot of scenes.flatMap((g) => g.shots)) {
      if (only.length && !only.some((w) => shot.png.includes(w))) continue;
      const [width, height] = (shot.size || "1280x800").split("x").map(Number);
      const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1 });
      watch(page, shot.png);
      await page.goto(`${url}?${query(shot)}`);
      await page.waitForSelector("html[data-mockup-ready]", { timeout: 5000 });
      if (shot.select) await page.selectOption(shot.select[0], shot.select[1], { timeout: 2000 });
      if (shot.hover) await page.locator(shot.hover).hover({ timeout: 2000 });
      else await page.mouse.move(width - 1, height - 1);
      await page.waitForTimeout(150);
      await page.screenshot({ path: path.join(out, shot.png + ".png") });
      console.log("shot", shot.png);
      await page.close();
    }
    if (!only.length && out === dir) writeTable(scenes);
  } catch (e) {
    errors.push(String(e.message || e));
  } finally {
    await browser.close();
  }
  if (errors.length) {
    console.error("mockup gallery: failed\n  " + errors.join("\n  "));
    process.exit(1);
  }
})();
